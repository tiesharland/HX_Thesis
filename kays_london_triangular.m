    %% ---- Nested validation plot function ---- %%

    function plot_validation(sigmas, curves, p_all, K_at_Re, ...
            sigma_q, Re, K_val, Re_vals_interp, p_Re, Re_labels, label)

        cols       = lines(numel(Re_vals_interp));
        sigma_plot = linspace(0, 1, 200);

        % --- Polynomial fits vs digitised data --- %
        figure('Name', sprintf('%s — Polynomial fits vs digitised data', label), ...
               'NumberTitle', 'off');
        hold on
        for i = 1:numel(Re_vals_interp)
            if isempty(sigmas{i}), continue; end
            scatter(sigmas{i}, curves{i}, 40, cols(i,:), 'filled', ...
                    'DisplayName', [Re_labels{i} ' (data)']);
            plot(sigma_plot, polyval(p_all{i}, sigma_plot), '-', ...
                 'Color', cols(i,:), 'LineWidth', 1.5, ...
                 'DisplayName', [Re_labels{i} ' (fit)']);
        end
        xline(sigma_q, '--k', sprintf('\\sigma=%.3f', sigma_q), ...
              'LabelHorizontalAlignment', 'left');
        scatter(sigma_q, K_val, 100, 'k', 'x', 'LineWidth', 2, ...
                'DisplayName', sprintf('Query (Re=%.0f) -> %s=%.4f', Re, label, K_val));
        xlabel('\sigma (void fraction)')
        ylabel(label)
        title(sprintf('%s polynomial fits (order %d) — Kays & London triangular fins', ...
              label, poly_order))
        legend('Location', 'best', 'FontSize', 8)
        grid on

        % --- Interpolation across Re at query sigma --- %
        Re_plot    = logspace(0, 6, 500);
        % K_plot     = interp1(Re_vals_ln, K_at_Re, log(Re_plot), 'pchip');
        K_plot = polyval(p_Re, log(Re_plot));
        % K_plot = polyval(p_Re, Re_plot);

        figure('Name', sprintf('%s vs Re at query sigma', label), 'NumberTitle', 'off');
        hold on
        plot(Re_plot, K_plot, 'b-', 'LineWidth', 1.5, ...
             'DisplayName', sprintf('%s (Polynomial fit over ln(Re), n=3)', label))  %'%s (PCHIP over ln Re)'
        scatter(Re_vals_interp, K_at_Re, 60, 'b', 'filled', ...
                'DisplayName', sprintf('%s at Re nodes', label))
        scatter(Re, K_val, 100, 'k', 'x', 'LineWidth', 2, ...
                'DisplayName', sprintf('Query Re=%.0f -> %s=%.4f', Re, label, K_val))
        % set(gca, 'XScale', 'log')
        xlim([0 1.5e4])
        xlabel('Re')
        ylabel(label)
        title(sprintf('%s vs Re at \\sigma = %.3f', label, sigma_q))
        legend('Location', 'best')
        grid on

    end

