    %% ---- Parse interleaved raw arrays into sorted [sigma, K] columns ---- %%

    function [s, K] = parse_raw(raw)
        raw = raw(:);
        s   = raw(1:2:end);
        K   = raw(2:2:end);
        [s, idx] = sort(s);
        K   = K(idx);
    end

